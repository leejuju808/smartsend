-- ============================================================================
-- PART 1 — OSHA INCIDENTS TABLE
-- ============================================================================
-- Tracks workplace injuries and incidents for OSHA compliance

CREATE TABLE IF NOT EXISTS public.osha_incidents (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id uuid NOT NULL REFERENCES public.roofing_companies(id) ON DELETE CASCADE,
  job_id uuid REFERENCES public.jobs(id) ON DELETE SET NULL,
  employee_id uuid REFERENCES public.workforce_employees(id) ON DELETE SET NULL,
  
  -- Incident Details
  description text NOT NULL,
  severity text NOT NULL CHECK (severity IN ('minor', 'moderate', 'serious', 'fatal')),
  injury_type text, -- cut, fall, strain, burn, etc.
  body_part text, -- hand, leg, back, head, etc.
  
  -- Documentation
  photos text[], -- Array of photo URLs
  video_url text,
  location text, -- Where on jobsite
  date timestamptz NOT NULL,
  
  -- AI-Generated Compliance Fields
  osha_classification text, -- Generated by AI
  root_cause_summary text, -- Generated by AI
  corrective_action_plan text, -- Generated by AI
  osha_301_completed boolean DEFAULT false,
  
  -- Metadata
  reported_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_osha_incidents_company ON public.osha_incidents(company_id);
CREATE INDEX IF NOT EXISTS idx_osha_incidents_job ON public.osha_incidents(job_id) WHERE job_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_osha_incidents_employee ON public.osha_incidents(employee_id) WHERE employee_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_osha_incidents_date ON public.osha_incidents(company_id, date DESC);
CREATE INDEX IF NOT EXISTS idx_osha_incidents_severity ON public.osha_incidents(company_id, severity);

COMMENT ON TABLE public.osha_incidents IS 'Tracks workplace injuries and incidents for OSHA compliance (Block 254600)';
COMMENT ON COLUMN public.osha_incidents.severity IS 'Severity: minor, moderate, serious, fatal';
COMMENT ON COLUMN public.osha_incidents.osha_301_completed IS 'Whether OSHA 301 form has been completed for this incident';

-- ============================================================================
-- PART 2 — OSHA LOGS TABLE
-- ============================================================================
-- Stores OSHA 300, 301, and 300A forms

CREATE TABLE IF NOT EXISTS public.osha_logs (
