-- Function: Generate OSHA 300 Log (Annual Log of Work-Related Injuries and Illnesses)
CREATE OR REPLACE FUNCTION public.generate_osha_300_log(
  p_company_id uuid,
  p_year int
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_log_id uuid;
  v_incidents jsonb;
BEGIN
  -- Collect all recordable incidents for the year
  SELECT jsonb_agg(
    jsonb_build_object(
      'id', id,
      'date', date,
      'employee_name', (SELECT first_name || ' ' || last_name FROM public.workforce_employees WHERE id = oi.employee_id),
      'job_location', (SELECT notes FROM public.jobs WHERE id = oi.job_id),
      'description', description,
      'injury_type', injury_type,
      'body_part', body_part,
      'severity', severity
    )
    ORDER BY date
  )
  INTO v_incidents
  FROM public.osha_incidents oi
  WHERE oi.company_id = p_company_id
    AND EXTRACT(YEAR FROM oi.date) = p_year
    AND oi.severity IN ('moderate', 'serious', 'fatal'); -- Only recordable incidents

  -- Create OSHA 300 log entry
  INSERT INTO public.osha_logs (
    company_id,
    form_type,
    year,
    data,
    generated_by
  )
  VALUES (
    p_company_id,
    'OSHA_300',
    p_year,
    jsonb_build_object(
      'incidents', COALESCE(v_incidents, '[]'::jsonb),
      'total_recordable_cases', jsonb_array_length(COALESCE(v_incidents, '[]'::jsonb)),
      'generated_at', now()
    ),
    auth.uid()
  )
  RETURNING id INTO v_log_id;

  RETURN v_log_id;
END;
$$;

