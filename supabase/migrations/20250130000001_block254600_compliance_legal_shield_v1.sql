    CASE 
      WHEN expires_on IS NULL THEN false
      WHEN expires_on < CURRENT_DATE THEN true
      ELSE false
    END
  ) STORED,
  
  -- Metadata
  notes text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

