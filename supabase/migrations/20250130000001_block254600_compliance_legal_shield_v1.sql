-- Function: Check for PPE Violations and Create Alerts
CREATE OR REPLACE FUNCTION public.check_ppe_violations(
  p_company_id uuid,
  p_days_back int DEFAULT 30
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_violation_count int;
  v_employee_id uuid;
  v_employee_name text;
BEGIN
  -- Find employees with multiple PPE violations in the time period
  FOR v_employee_id, v_violation_count IN
    SELECT employee_id, COUNT(*)
    FROM public.ppe_checks
    WHERE company_id = p_company_id
      AND compliant = false
      AND check_date >= CURRENT_DATE - (p_days_back || ' days')::interval
      AND employee_id IS NOT NULL
    GROUP BY employee_id
    HAVING COUNT(*) >= 3
  LOOP
    -- Get employee name
    SELECT first_name || ' ' || last_name INTO v_employee_name
    FROM public.workforce_employees
    WHERE id = v_employee_id;

    -- Create alert if it doesn't already exist
    INSERT INTO public.legal_risk_alerts (
      company_id,
      alert_type,
      severity,
      title,
      message,
      related_employee_id,
      metadata
    )
    VALUES (
      p_company_id,
      'ppe_violations',
      CASE
        WHEN v_violation_count >= 5 THEN 'critical'
        WHEN v_violation_count >= 3 THEN 'high'
        ELSE 'medium'
      END,
      'Repeated PPE Violations Detected',
      COALESCE(v_employee_name, 'Employee') || ' has ' || v_violation_count || ' PPE violations in the last ' || p_days_back || ' days. Recommend retraining and documentation.',
      v_employee_id,
      jsonb_build_object('violation_count', v_violation_count, 'days_back', p_days_back)
    )
    ON CONFLICT DO NOTHING;
  END LOOP;
END;
$$;

