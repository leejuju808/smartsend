-- Helper function to check company access
CREATE OR REPLACE FUNCTION public.user_has_company_access(_company_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.roofing_companies rc
    WHERE rc.id = _company_id
      AND (
        rc.owner_id = auth.uid()
        OR EXISTS (
          SELECT 1
          FROM public.workspace_members wm
          JOIN public.roofing_companies rc2 ON rc2.workspace_id = wm.workspace_id
          WHERE wm.user_id = auth.uid()
            AND rc2.id = _company_id
        )
      )
  );
$$;

