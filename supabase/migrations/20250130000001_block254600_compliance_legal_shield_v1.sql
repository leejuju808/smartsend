  created_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_osha_logs_company ON public.osha_logs(company_id);
CREATE INDEX IF NOT EXISTS idx_osha_logs_form_type ON public.osha_logs(company_id, form_type, year);
CREATE INDEX IF NOT EXISTS idx_osha_logs_year ON public.osha_logs(company_id, year DESC);

COMMENT ON TABLE public.osha_logs IS 'Stores OSHA 300, 301, and 300A forms (Block 254600)';
COMMENT ON COLUMN public.osha_logs.form_type IS 'Form type: OSHA_300, OSHA_301, OSHA_300A';
