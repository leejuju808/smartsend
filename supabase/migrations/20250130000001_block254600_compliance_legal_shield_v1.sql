-- PART 7 — SUBCONTRACTOR COMPLIANCE TABLE
-- ============================================================================
-- Tracks subcontractor compliance documents (W9, COI, Workers Comp, etc.)

CREATE TABLE IF NOT EXISTS public.subcontractor_compliance (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id uuid NOT NULL REFERENCES public.roofing_companies(id) ON DELETE CASCADE,
  subcontractor_id uuid, -- References subcontractors table if exists, or store name
  
  -- Subcontractor Info
  subcontractor_name text NOT NULL,
  contact_name text,
  contact_email text,
  contact_phone text,
  
  -- Compliance Documents
  w9_on_file boolean DEFAULT false,
  w9_url text,
  w9_expires_on date,
  
  coi_on_file boolean DEFAULT false, -- Certificate of Insurance
  coi_url text,
  coi_expires_on date,
  coi_coverage_amount numeric,
  
  workers_comp_on_file boolean DEFAULT false,
  workers_comp_url text,
  workers_comp_expires_on date,
  
  safety_certifications jsonb DEFAULT '[]'::jsonb, -- Array of certs
  
  -- Status
  is_compliant boolean GENERATED ALWAYS AS (
    CASE
      WHEN w9_on_file = false THEN false
      WHEN coi_on_file = false THEN false
      WHEN workers_comp_on_file = false THEN false
      WHEN coi_expires_on IS NOT NULL AND coi_expires_on < CURRENT_DATE THEN false
      WHEN workers_comp_expires_on IS NOT NULL AND workers_comp_expires_on < CURRENT_DATE THEN false
      ELSE true
    END
  ) STORED,
  
  -- Metadata
  notes text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_subcontractor_compliance_company ON public.subcontractor_compliance(company_id);
CREATE INDEX IF NOT EXISTS idx_subcontractor_compliance_compliant ON public.subcontractor_compliance(company_id, is_compliant);
CREATE INDEX IF NOT EXISTS idx_subcontractor_compliance_expires ON public.subcontractor_compliance(company_id, coi_expires_on, workers_comp_expires_on);

COMMENT ON TABLE public.subcontractor_compliance IS 'Tracks subcontractor compliance documents (Block 254600)';
COMMENT ON COLUMN public.subcontractor_compliance.is_compliant IS 'Computed: true if all required docs on file and not expired';

