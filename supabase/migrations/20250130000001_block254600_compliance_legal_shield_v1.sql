-- Function: Get Jobs Missing Daily Safety Logs
-- Returns jobs that need daily safety logs for today

CREATE OR REPLACE FUNCTION public.get_jobs_missing_safety_logs(
  p_company_id uuid,
  p_log_date date DEFAULT CURRENT_DATE
)
RETURNS TABLE (
  job_id uuid,
  job_notes text,
  crew_foreman_id uuid,
  foreman_name text
)
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
AS $$
BEGIN
  RETURN QUERY
  SELECT DISTINCT
    j.id AS job_id,
    j.notes AS job_notes,
    we.id AS crew_foreman_id,
    (we.first_name || ' ' || we.last_name) AS foreman_name
  FROM public.jobs j
  LEFT JOIN public.daily_safety_logs dsl ON dsl.job_id = j.id AND dsl.log_date = p_log_date
  LEFT JOIN public.crew_assignments ca ON ca.job_id = j.id
  LEFT JOIN public.workforce_employees we ON we.id = ca.employee_id AND we.role = 'foreman'
  WHERE dsl.id IS NULL -- No safety log for this date
    AND j.stage IN ('scheduled', 'in_progress') -- Only active jobs
    AND EXISTS (
      -- Verify company access through crew assignments
      SELECT 1
      FROM public.crew_assignments ca2
      JOIN public.workforce_employees we2 ON we2.id = ca2.employee_id
      WHERE ca2.job_id = j.id
        AND we2.company_id = p_company_id
    )
  ORDER BY j.id;
END;
$$;

