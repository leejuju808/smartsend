-- PART 15 — COMPLIANCE AUDIT DASHBOARD FUNCTION
-- ============================================================================

-- Function: Get Compliance Dashboard Data
CREATE OR REPLACE FUNCTION public.get_compliance_dashboard(
  p_company_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
AS $$
DECLARE
  v_result jsonb;
  v_safety_score numeric;
  v_incidents_this_year int;
  v_training_compliant_pct numeric;
  v_sub_compliance_pct numeric;
  v_hazards_unresolved int;
  v_osha_ready boolean;
BEGIN
  -- Calculate Safety Score (0-100)
  -- Based on: incidents, training compliance, PPE compliance, hazard resolution
  SELECT
    GREATEST(0, 100 - (
      (COUNT(*) FILTER (WHERE severity IN ('serious', 'fatal'))) * 10 +
      (COUNT(*) FILTER (WHERE severity = 'moderate')) * 5
    ))
  INTO v_safety_score
  FROM public.osha_incidents
  WHERE company_id = p_company_id
    AND EXTRACT(YEAR FROM date) = EXTRACT(YEAR FROM CURRENT_DATE);

  -- Count incidents this year
  SELECT COUNT(*) INTO v_incidents_this_year
  FROM public.osha_incidents
  WHERE company_id = p_company_id
    AND EXTRACT(YEAR FROM date) = EXTRACT(YEAR FROM CURRENT_DATE);

  -- Calculate training compliance percentage
  SELECT
    CASE
      WHEN COUNT(*) = 0 THEN 100
      ELSE ROUND((COUNT(*) FILTER (WHERE is_expired = false AND is_required = true)::numeric / 
                  NULLIF(COUNT(*) FILTER (WHERE is_required = true), 0)) * 100, 1)
    END
  INTO v_training_compliant_pct
  FROM public.training_records
  WHERE company_id = p_company_id;

  -- Calculate subcontractor compliance percentage
  SELECT
    CASE
      WHEN COUNT(*) = 0 THEN 100
      ELSE ROUND((COUNT(*) FILTER (WHERE is_compliant = true)::numeric / 
                  NULLIF(COUNT(*), 0)) * 100, 1)
    END
  INTO v_sub_compliance_pct
  FROM public.subcontractor_compliance
  WHERE company_id = p_company_id;

  -- Count unresolved hazards
  SELECT COUNT(*) INTO v_hazards_unresolved
  FROM public.hazard_reports
  WHERE company_id = p_company_id
    AND resolved = false;

  -- Check OSHA readiness (has logs for current year)
  SELECT EXISTS (
    SELECT 1
    FROM public.osha_logs
    WHERE company_id = p_company_id
      AND form_type = 'OSHA_300A'
      AND year = EXTRACT(YEAR FROM CURRENT_DATE)
  ) INTO v_osha_ready;

  -- Build result
  v_result := jsonb_build_object(
    'safety_score', COALESCE(v_safety_score, 100),
    'incidents_this_year', v_incidents_this_year,
    'training_compliant_pct', COALESCE(v_training_compliant_pct, 100),
    'sub_compliance_pct', COALESCE(v_sub_compliance_pct, 100),
    'hazards_unresolved', v_hazards_unresolved,
    'osha_requirements_ready', v_osha_ready,
    'generated_at', now()
  );

  RETURN v_result;
END;
$$;

