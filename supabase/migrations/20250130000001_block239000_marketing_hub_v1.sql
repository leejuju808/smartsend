-- PART 1 — CREATE marketing_campaigns TABLE
-- ============================================================================
-- Campaigns define the marketing automation flows

CREATE TABLE IF NOT EXISTS public.marketing_campaigns (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  company_id uuid REFERENCES public.roofing_companies(id) ON DELETE SET NULL,
  
  -- Campaign Identity
  name text NOT NULL,                    -- "Review Request - Google + Yelp"
  type text NOT NULL CHECK (type IN (
    'review',
    'referral',
    'upsell',
    'reactivation',
    'nurture',
    'warranty',
    'anniversary',
    'storm_followup'
  )),
  
  -- Campaign Status
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused', 'archived')),
  
  -- Trigger Configuration
  trigger_type text NOT NULL CHECK (trigger_type IN (
    'job_completed',
    'lead_status_changed',
    'time_delay',
    'manual',
    'lead_inactive',
    'warranty_expiring',
    'anniversary',
    'weather_event'
  )),
  trigger_config jsonb DEFAULT '{}'::jsonb, -- e.g., {"delay_days": 30, "status": "cold"}
  
  -- Campaign Settings
  is_template boolean DEFAULT false,      -- Pre-built template campaigns
  is_ai_generated boolean DEFAULT false, -- Generated by AI campaign builder
  
  -- Metadata
  metadata jsonb DEFAULT '{}'::jsonb,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_marketing_campaigns_workspace ON public.marketing_campaigns(workspace_id);
CREATE INDEX IF NOT EXISTS idx_marketing_campaigns_company ON public.marketing_campaigns(company_id) WHERE company_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_marketing_campaigns_type ON public.marketing_campaigns(type);
CREATE INDEX IF NOT EXISTS idx_marketing_campaigns_status ON public.marketing_campaigns(status);
CREATE INDEX IF NOT EXISTS idx_marketing_campaigns_trigger ON public.marketing_campaigns(trigger_type);
CREATE INDEX IF NOT EXISTS idx_marketing_campaigns_template ON public.marketing_campaigns(is_template) WHERE is_template = true;

COMMENT ON TABLE public.marketing_campaigns IS 'Marketing automation campaigns (Block 239000)';

-- ============================================================================
-- PART 2 — CREATE marketing_steps TABLE
-- ============================================================================
-- Steps define the sequence of messages in a campaign

CREATE TABLE IF NOT EXISTS public.marketing_steps (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  campaign_id uuid NOT NULL REFERENCES public.marketing_campaigns(id) ON DELETE CASCADE,
  
  -- Step Order
  step_order int NOT NULL,                -- 1, 2, 3, etc.
  
  -- Timing
  delay_hours int NOT NULL DEFAULT 0,    -- Hours to wait after previous step (or trigger)
  
  -- Channel & Content
  channel text NOT NULL CHECK (channel IN ('email', 'sms')),
  subject text,                           -- For email
  content text NOT NULL,                  -- Message content
  
  -- Personalization
  personalization_tokens jsonb DEFAULT '{}'::jsonb, -- Available tokens: {{FIRST_NAME}}, {{JOB_TYPE}}, etc.
  
  -- Settings
  require_response boolean DEFAULT false, -- Pause campaign if customer responds
  skip_if_condition jsonb DEFAULT '{}'::jsonb, -- Conditions to skip this step
  
  -- Metadata
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_marketing_steps_campaign ON public.marketing_steps(campaign_id);
CREATE INDEX IF NOT EXISTS idx_marketing_steps_order ON public.marketing_steps(campaign_id, step_order);

COMMENT ON TABLE public.marketing_steps IS 'Individual steps within marketing campaigns (Block 239000)';

