-- Function to trigger a campaign for a target
CREATE OR REPLACE FUNCTION public.trigger_marketing_campaign(
  p_campaign_id uuid,
  p_lead_id uuid DEFAULT NULL,
  p_homeowner_id uuid DEFAULT NULL,
  p_job_id uuid DEFAULT NULL
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_instance_id uuid;
  v_campaign RECORD;
  v_first_step RECORD;
BEGIN
  -- Get campaign details
  SELECT * INTO v_campaign
  FROM public.marketing_campaigns
  WHERE id = p_campaign_id AND status = 'active';
  
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Campaign not found or not active';
  END IF;
  
  -- Check if instance already exists (prevent duplicates)
  SELECT id INTO v_instance_id
  FROM public.marketing_campaign_instances
  WHERE campaign_id = p_campaign_id
    AND (
      (p_lead_id IS NOT NULL AND lead_id = p_lead_id) OR
      (p_homeowner_id IS NOT NULL AND homeowner_id = p_homeowner_id) OR
      (p_job_id IS NOT NULL AND job_id = p_job_id)
    )
    AND status IN ('active', 'paused');
  
  IF v_instance_id IS NOT NULL THEN
    RETURN v_instance_id; -- Return existing instance
  END IF;
  
  -- Get first step timing
  SELECT delay_hours INTO v_first_step
  FROM public.marketing_steps
  WHERE campaign_id = p_campaign_id
  ORDER BY step_order ASC
  LIMIT 1;
  
  -- Create campaign instance
  INSERT INTO public.marketing_campaign_instances (
    campaign_id,
    lead_id,
    homeowner_id,
    job_id,
    status,
    current_step,
    triggered_at,
    next_step_at
  ) VALUES (
    p_campaign_id,
    p_lead_id,
    p_homeowner_id,
    p_job_id,
    'active',
    1,
    now(),
    now() + COALESCE((v_first_step.delay_hours || ' hours')::interval, '0 hours'::interval)
  )
  RETURNING id INTO v_instance_id;
  
  RETURN v_instance_id;
END;
$$;

-- Function to process next step in a campaign instance
CREATE OR REPLACE FUNCTION public.process_marketing_campaign_step(
  p_instance_id uuid
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_instance RECORD;
  v_campaign RECORD;
  v_step RECORD;
  v_next_step RECORD;
  v_lead RECORD;
  v_homeowner RECORD;
  v_job RECORD;
  v_content text;
  v_subject text;
BEGIN
  -- Get instance details
  SELECT * INTO v_instance
  FROM public.marketing_campaign_instances
  WHERE id = p_instance_id AND status = 'active';
  
  IF NOT FOUND THEN
    RETURN false;
  END IF;
  
  -- Check if it's time to process
  IF v_instance.next_step_at > now() THEN
    RETURN false; -- Not time yet
  END IF;
  
  -- Get campaign
  SELECT * INTO v_campaign
  FROM public.marketing_campaigns
  WHERE id = v_instance.campaign_id;
  
  -- Get current step
  SELECT * INTO v_step
  FROM public.marketing_steps
  WHERE campaign_id = v_instance.campaign_id
    AND step_order = v_instance.current_step;
  
  IF NOT FOUND THEN
    -- No more steps, mark as completed
    UPDATE public.marketing_campaign_instances
    SET status = 'completed', completed_at = now()
    WHERE id = p_instance_id;
    RETURN true;
  END IF;
  
  -- Get target information for personalization
  IF v_instance.lead_id IS NOT NULL THEN
    SELECT * INTO v_lead FROM public.leads WHERE id = v_instance.lead_id;
  END IF;
  
  IF v_instance.homeowner_id IS NOT NULL THEN
    SELECT * INTO v_homeowner FROM public.homeowners WHERE id = v_instance.homeowner_id;
  END IF;
  
  IF v_instance.job_id IS NOT NULL THEN
    SELECT * INTO v_job FROM public.roofing_jobs WHERE id = v_instance.job_id;
  END IF;
  
  -- Personalize content (simple token replacement)
  v_content := v_step.content;
  v_subject := v_step.subject;
  
  -- Replace tokens (basic implementation - can be enhanced)
  IF v_lead IS NOT NULL THEN
    v_content := replace(v_content, '{{FIRST_NAME}}', COALESCE(v_lead.first_name, ''));
    v_content := replace(v_content, '{{LAST_NAME}}', COALESCE(v_lead.last_name, ''));
    v_content := replace(v_content, '{{EMAIL}}', COALESCE(v_lead.email, ''));
    IF v_subject IS NOT NULL THEN
      v_subject := replace(v_subject, '{{FIRST_NAME}}', COALESCE(v_lead.first_name, ''));
    END IF;
  END IF;
  
  -- Log the step (actual sending happens via API/webhook)
  INSERT INTO public.marketing_logs (
    campaign_id,
    lead_id,
    homeowner_id,
    job_id,
    step_id,
    step_number,
    status,
    channel,
    sent_at
  ) VALUES (
    v_instance.campaign_id,
    v_instance.lead_id,
    v_instance.homeowner_id,
    v_instance.job_id,
    v_step.id,
    v_instance.current_step,
    'sent',
    v_step.channel,
    now()
  );
  
  -- Get next step
  SELECT * INTO v_next_step
  FROM public.marketing_steps
  WHERE campaign_id = v_instance.campaign_id
    AND step_order = v_instance.current_step + 1;
  
  -- Update instance
  IF v_next_step IS NOT NULL THEN
    UPDATE public.marketing_campaign_instances
    SET 
      current_step = v_instance.current_step + 1,
      next_step_at = now() + (v_next_step.delay_hours || ' hours')::interval,
      updated_at = now()
    WHERE id = p_instance_id;
  ELSE
    -- No more steps
    UPDATE public.marketing_campaign_instances
    SET 
      status = 'completed',
      completed_at = now(),
      updated_at = now()
    WHERE id = p_instance_id;
  END IF;
  
  RETURN true;
END;
$$;

