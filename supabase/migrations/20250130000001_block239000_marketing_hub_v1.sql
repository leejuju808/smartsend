-- Campaigns: Users can access campaigns in their workspace
CREATE POLICY "marketing_campaigns_workspace_access"
  ON public.marketing_campaigns
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM public.workspace_members wm
      WHERE wm.workspace_id = marketing_campaigns.workspace_id
        AND wm.user_id = auth.uid()
    )
  );

-- Steps: Inherit from campaign access
CREATE POLICY "marketing_steps_campaign_access"
  ON public.marketing_steps
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM public.marketing_campaigns mc
      JOIN public.workspace_members wm ON wm.workspace_id = mc.workspace_id
      WHERE mc.id = marketing_steps.campaign_id
        AND wm.user_id = auth.uid()
    )
  );

-- Logs: Inherit from campaign access
