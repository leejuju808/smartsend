-- Trigger: When job is completed, start review campaign
CREATE OR REPLACE FUNCTION public.trigger_review_campaign_on_job_completion()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_campaign_id uuid;
  v_lead_id uuid;
BEGIN
  -- Only trigger when status changes to 'completed'
  IF NEW.status != 'completed' OR OLD.status = 'completed' THEN
    RETURN NEW;
  END IF;
  
  -- Find review campaign for this workspace
  SELECT id INTO v_campaign_id
  FROM public.marketing_campaigns
  WHERE workspace_id = NEW.workspace_id
    AND type = 'review'
    AND trigger_type = 'job_completed'
    AND status = 'active'
  LIMIT 1;
  
  IF v_campaign_id IS NOT NULL THEN
    -- Get lead_id from job
    SELECT lead_id INTO v_lead_id
    FROM public.roofing_jobs
    WHERE id = NEW.id;
    
    IF v_lead_id IS NOT NULL THEN
      -- Trigger the campaign
      PERFORM public.trigger_marketing_campaign(
        v_campaign_id,
        p_lead_id := v_lead_id,
        p_job_id := NEW.id
      );
    END IF;
  END IF;
  
  RETURN NEW;
END;
$$;

-- Apply trigger to roofing_jobs (if table exists)
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'roofing_jobs') THEN
    DROP TRIGGER IF EXISTS trg_review_campaign_on_job_completion ON public.roofing_jobs;
    CREATE TRIGGER trg_review_campaign_on_job_completion
    AFTER UPDATE OF status ON public.roofing_jobs
    FOR EACH ROW
    EXECUTE FUNCTION public.trigger_review_campaign_on_job_completion();
  END IF;
END $$;

