-- Function to calculate and update domain reputation
CREATE OR REPLACE FUNCTION public.update_domain_reputation(p_domain_id uuid)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  v_total_sent integer;
  v_total_delivered integer;
  v_total_opened integer;
  v_total_replied integer;
  v_total_bounced integer;
  v_total_complained integer;
  v_deliverability_rate numeric;
  v_open_rate numeric;
  v_reply_rate numeric;
  v_bounce_rate numeric;
  v_complaint_rate numeric;
  v_reputation_score numeric;
  v_sending_reputation text;
BEGIN
  -- Aggregate metrics from warmup_logs
  SELECT 
    COALESCE(SUM(sent), 0),
    COALESCE(SUM(delivered), 0),
    COALESCE(SUM(opened), 0),
    COALESCE(SUM(replied), 0),
    COALESCE(SUM(bounced), 0),
    COALESCE(SUM(complained), 0)
  INTO 
    v_total_sent,
    v_total_delivered,
    v_total_opened,
    v_total_replied,
    v_total_bounced,
    v_total_complained
  FROM public.warmup_logs
  WHERE domain_id = p_domain_id;
  
  -- Calculate rates
  v_deliverability_rate := CASE WHEN v_total_sent > 0 THEN (v_total_delivered::numeric / v_total_sent::numeric * 100) ELSE 0 END;
  v_open_rate := CASE WHEN v_total_delivered > 0 THEN (v_total_opened::numeric / v_total_delivered::numeric * 100) ELSE 0 END;
  v_reply_rate := CASE WHEN v_total_delivered > 0 THEN (v_total_replied::numeric / v_total_delivered::numeric * 100) ELSE 0 END;
  v_bounce_rate := CASE WHEN v_total_sent > 0 THEN (v_total_bounced::numeric / v_total_sent::numeric * 100) ELSE 0 END;
  v_complaint_rate := CASE WHEN v_total_sent > 0 THEN (v_total_complained::numeric / v_total_sent::numeric * 100) ELSE 0 END;
  
  -- Calculate reputation score (0-100)
  -- Formula: deliverability (40%) + open rate (30%) + reply rate (20%) - bounce rate (5%) - complaint rate (5%)
  v_reputation_score := 
    (v_deliverability_rate * 0.4) +
    (v_open_rate * 0.3) +
    (v_reply_rate * 0.2) -
    (v_bounce_rate * 0.05) -
    (v_complaint_rate * 0.05);
  
  -- Clamp to 0-100
  v_reputation_score := GREATEST(0, LEAST(100, v_reputation_score));
  
  -- Determine reputation tier
  IF v_reputation_score >= 80 AND v_bounce_rate < 2 AND v_complaint_rate < 0.1 THEN
    v_sending_reputation := 'excellent';
  ELSIF v_reputation_score >= 60 AND v_bounce_rate < 5 AND v_complaint_rate < 0.5 THEN
    v_sending_reputation := 'good';
  ELSIF v_reputation_score >= 40 AND v_bounce_rate < 10 THEN
    v_sending_reputation := 'fair';
  ELSE
    v_sending_reputation := 'poor';
  END IF;
  
  -- Update sending_domains
  UPDATE public.sending_domains
  SET
    total_sent = v_total_sent,
    total_delivered = v_total_delivered,
    total_opened = v_total_opened,
    total_replied = v_total_replied,
    total_bounced = v_total_bounced,
    total_complained = v_total_complained,
    deliverability_rate = v_deliverability_rate,
    open_rate = v_open_rate,
    reply_rate = v_reply_rate,
    bounce_rate = v_bounce_rate,
    complaint_rate = v_complaint_rate,
    reputation_score = v_reputation_score,
    sending_reputation = v_sending_reputation
  WHERE id = p_domain_id;
END;
$$;

COMMENT ON FUNCTION public.update_domain_reputation IS 'Calculates and updates domain reputation based on warm-up logs (Block 76000)';

-- Function to initialize warm-up schedule
CREATE OR REPLACE FUNCTION public.initialize_warmup_schedule(p_domain_id uuid)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  v_day integer;
  v_emails integer;
BEGIN
  -- Standard warm-up schedule: gradual increase over 30 days
  -- Day 1: 3, Day 2: 5, Day 3: 8, Day 4: 12, Day 5: 20, Day 10: 35, Day 20: 60, Day 30: 100
  FOR v_day IN 1..30 LOOP
    CASE v_day
      WHEN 1 THEN v_emails := 3;
      WHEN 2 THEN v_emails := 5;
      WHEN 3 THEN v_emails := 8;
      WHEN 4 THEN v_emails := 12;
      WHEN 5 THEN v_emails := 20;
      WHEN 6 THEN v_emails := 25;
      WHEN 7 THEN v_emails := 30;
      WHEN 8 THEN v_emails := 32;
      WHEN 9 THEN v_emails := 34;
      WHEN 10 THEN v_emails := 35;
      WHEN 11 THEN v_emails := 38;
      WHEN 12 THEN v_emails := 40;
      WHEN 13 THEN v_emails := 42;
      WHEN 14 THEN v_emails := 45;
      WHEN 15 THEN v_emails := 48;
      WHEN 16 THEN v_emails := 50;
      WHEN 17 THEN v_emails := 52;
      WHEN 18 THEN v_emails := 55;
      WHEN 19 THEN v_emails := 58;
      WHEN 20 THEN v_emails := 60;
      WHEN 21 THEN v_emails := 65;
      WHEN 22 THEN v_emails := 70;
      WHEN 23 THEN v_emails := 75;
      WHEN 24 THEN v_emails := 80;
      WHEN 25 THEN v_emails := 85;
      WHEN 26 THEN v_emails := 90;
      WHEN 27 THEN v_emails := 95;
      WHEN 28 THEN v_emails := 98;
      WHEN 29 THEN v_emails := 99;
      WHEN 30 THEN v_emails := 100;
      ELSE v_emails := 100;
    END CASE;
    
    INSERT INTO public.warmup_schedule (domain_id, day, emails_to_send)
    VALUES (p_domain_id, v_day, v_emails)
    ON CONFLICT (domain_id, day) DO NOTHING;
  END LOOP;
  
  -- Update domain warmup status
  UPDATE public.sending_domains
  SET warmup_status = 'warming', warmup_started_at = now()
  WHERE id = p_domain_id;
END;
$$;

COMMENT ON FUNCTION public.initialize_warmup_schedule IS 'Initializes 30-day warm-up schedule for a domain (Block 76000)';

