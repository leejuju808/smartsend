-- ============================================================================
-- PART 1 — SENDING DOMAINS TABLE
-- ============================================================================
-- Domains connected by roofing company/org for email sending

CREATE TABLE IF NOT EXISTS public.sending_domains (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id uuid REFERENCES public.organizations(id) ON DELETE CASCADE,
  roofing_company_id uuid REFERENCES public.roofing_companies(id) ON DELETE CASCADE,
  
  -- Domain Information
  domain text NOT NULL,                    -- e.g., "smithroofing.com"
  
  -- DNS Records (generated by SmartSend)
  dkim_record text,                        -- DKIM public key record
  dkim_selector text DEFAULT 'default',    -- DKIM selector
  spf_record text,                         -- SPF record value
  dmarc_record text,                       -- DMARC policy record
  
  -- DNS Verification Status
  dns_status text DEFAULT 'not_connected' CHECK (dns_status IN ('not_connected', 'partially_connected', 'fully_authenticated')),
  spf_verified boolean DEFAULT false,
  dkim_verified boolean DEFAULT false,
  dmarc_verified boolean DEFAULT false,
  last_dns_check_at timestamptz,
  
  -- Warm-Up Status
  warmup_status text DEFAULT 'not_started' CHECK (warmup_status IN ('not_started', 'warming', 'ready', 'paused', 'failed')),
  warmup_started_at timestamptz,
  warmup_completed_at timestamptz,
  
  -- Sending Reputation
  sending_reputation text DEFAULT 'poor' CHECK (sending_reputation IN ('poor', 'fair', 'good', 'excellent')),
  reputation_score numeric DEFAULT 0 CHECK (reputation_score >= 0 AND reputation_score <= 100),
  
  -- Reputation Metrics (calculated from warmup_logs)
  total_sent integer DEFAULT 0,
  total_delivered integer DEFAULT 0,
  total_opened integer DEFAULT 0,
  total_replied integer DEFAULT 0,
  total_bounced integer DEFAULT 0,
  total_complained integer DEFAULT 0,
  deliverability_rate numeric DEFAULT 0,   -- delivered / sent
  open_rate numeric DEFAULT 0,             -- opened / delivered
  reply_rate numeric DEFAULT 0,             -- replied / delivered
  bounce_rate numeric DEFAULT 0,            -- bounced / sent
  complaint_rate numeric DEFAULT 0,         -- complained / sent
  
  -- Throttle Status
  is_throttled boolean DEFAULT false,
  throttle_reason text,
  throttle_until timestamptz,
  
  -- Metadata
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  
  -- Ensure unique domain per org
  CONSTRAINT unique_domain_per_org UNIQUE (org_id, domain)
);

CREATE INDEX IF NOT EXISTS idx_sending_domains_org ON public.sending_domains(org_id);
CREATE INDEX IF NOT EXISTS idx_sending_domains_company ON public.sending_domains(roofing_company_id) WHERE roofing_company_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_sending_domains_domain ON public.sending_domains(domain);
CREATE INDEX IF NOT EXISTS idx_sending_domains_warmup_status ON public.sending_domains(warmup_status);
CREATE INDEX IF NOT EXISTS idx_sending_domains_reputation ON public.sending_domains(sending_reputation, reputation_score);
CREATE INDEX IF NOT EXISTS idx_sending_domains_throttled ON public.sending_domains(is_throttled, throttle_until) WHERE is_throttled = true;

COMMENT ON TABLE public.sending_domains IS 'Sending domains for email deliverability with DNS verification and warm-up tracking (Block 76000)';

-- ============================================================================
-- PART 2 — WARM-UP SCHEDULE TABLE
-- ============================================================================
-- Daily schedule for domain warm-up emails

CREATE TABLE IF NOT EXISTS public.warmup_schedule (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  domain_id uuid NOT NULL REFERENCES public.sending_domains(id) ON DELETE CASCADE,
  
  -- Schedule Details
  day integer NOT NULL CHECK (day > 0),    -- Day number (1, 2, 3, ...)
  emails_to_send integer NOT NULL CHECK (emails_to_send > 0),
  
  -- Status
  status text DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'skipped', 'failed')),
  sent_at timestamptz,
  
  -- Metadata
  created_at timestamptz NOT NULL DEFAULT now(),
  
  -- Ensure unique day per domain
  CONSTRAINT unique_day_per_domain UNIQUE (domain_id, day)
);

CREATE INDEX IF NOT EXISTS idx_warmup_schedule_domain ON public.warmup_schedule(domain_id, day);
CREATE INDEX IF NOT EXISTS idx_warmup_schedule_status ON public.warmup_schedule(status) WHERE status = 'pending';

COMMENT ON TABLE public.warmup_schedule IS 'Daily warm-up email schedule for sending domains (Block 76000)';

-- ============================================================================
-- PART 3 — WARM-UP LOGS TABLE
-- ============================================================================
-- Detailed logs of warm-up email sends and results

CREATE TABLE IF NOT EXISTS public.warmup_logs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  domain_id uuid NOT NULL REFERENCES public.sending_domains(id) ON DELETE CASCADE,
  schedule_id uuid REFERENCES public.warmup_schedule(id) ON DELETE SET NULL,
  
  -- Send Metrics
  sent integer DEFAULT 0,
  delivered integer DEFAULT 0,
  opened integer DEFAULT 0,
  replied integer DEFAULT 0,
  bounced integer DEFAULT 0,
  complained integer DEFAULT 0,
  marked_spam integer DEFAULT 0,
  
  -- Calculated Rates
  deliverability_rate numeric,
  open_rate numeric,
  reply_rate numeric,
  bounce_rate numeric,
  complaint_rate numeric,
  
  -- Provider Feedback
  gmail_feedback jsonb DEFAULT '{}'::jsonb,    -- Gmail-specific feedback
  outlook_feedback jsonb DEFAULT '{}'::jsonb,  -- Outlook-specific feedback
  spam_score numeric,                          -- Overall spam score (0-100)
  
  -- Timestamp
  log_date date NOT NULL DEFAULT CURRENT_DATE,
  timestamp timestamptz NOT NULL DEFAULT now(),
  
  -- Ensure one log per domain per day
  CONSTRAINT unique_log_per_domain_per_day UNIQUE (domain_id, log_date)
);

CREATE INDEX IF NOT EXISTS idx_warmup_logs_domain ON public.warmup_logs(domain_id, log_date DESC);
CREATE INDEX IF NOT EXISTS idx_warmup_logs_timestamp ON public.warmup_logs(timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_warmup_logs_schedule ON public.warmup_logs(schedule_id) WHERE schedule_id IS NOT NULL;

COMMENT ON TABLE public.warmup_logs IS 'Daily warm-up email logs with deliverability metrics (Block 76000)';

-- ============================================================================
-- PART 4 — SEND QUEUE TABLE
-- ============================================================================
-- Queue for actual campaign emails with domain rotation and reputation checks

CREATE TABLE IF NOT EXISTS public.send_queue (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id uuid REFERENCES public.organizations(id) ON DELETE CASCADE,
  domain_id uuid REFERENCES public.sending_domains(id) ON DELETE SET NULL,
  campaign_id uuid,                         -- References campaigns table (if exists)
  
  -- Email Details
  recipient text NOT NULL,
  subject text NOT NULL,
  body text NOT NULL,
  body_html text,
  
  -- Sending Configuration
  from_email text,                          -- Override from address
  from_name text,                           -- Override from name
  reply_to text,
  
  -- Status & Retry Logic
  status text DEFAULT 'pending' CHECK (status IN ('pending', 'queued', 'sending', 'sent', 'failed', 'throttled', 'skipped')),
  retries integer DEFAULT 0,
  max_retries integer DEFAULT 3,
  error_message text,
  
  -- Scheduling
  scheduled_at timestamptz DEFAULT now(),
  sent_at timestamptz,
  
  -- Spam Score (pre-send check)
  spam_score numeric,
  spam_score_details jsonb DEFAULT '{}'::jsonb,
  
  -- Metadata
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_send_queue_org ON public.send_queue(org_id);
CREATE INDEX IF NOT EXISTS idx_send_queue_domain ON public.send_queue(domain_id) WHERE domain_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_send_queue_status ON public.send_queue(status, scheduled_at) WHERE status IN ('pending', 'queued');
CREATE INDEX IF NOT EXISTS idx_send_queue_campaign ON public.send_queue(campaign_id) WHERE campaign_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_send_queue_scheduled ON public.send_queue(scheduled_at) WHERE status IN ('pending', 'queued');

COMMENT ON TABLE public.send_queue IS 'Email send queue with domain rotation and reputation-based throttling (Block 76000)';

