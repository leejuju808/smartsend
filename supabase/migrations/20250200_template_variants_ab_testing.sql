-- Helper view to pick winners per campaign (optional)
create or replace view variant_winners as
select campaign_id, variant_id
from (
  select vm.*, row_number() over (partition by campaign_id order by reply_rate desc nulls last, sent desc) as rk
  from variant_metrics vm
) x
where rk = 1 and sent >= 50; -- only if enough volume